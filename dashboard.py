import streamlit as st
import pandas as pd
import numpy as np

st.set_page_config(
    page_title="EV BMS Simulation",
    layout="wide"
)

# =====================================================
# TITLE
# =====================================================

st.title("EV Battery Management System")
st.subheader("Lithium-Ion Battery Simulation")


# =====================================================
# BATTERY PARAMETERS
# =====================================================

rated_capacity = 3.0       # Ah
initial_soh = 100.0        # %
internal_resistance = 0.02 # Ohm
thermal_capacity = 500.0


# =====================================================
# SIDEBAR
# =====================================================

st.sidebar.header("Battery Controls")
mode = st.sidebar.selectbox(
    "Operation Mode",
    ["Discharging", "Charging"]
)

soc = st.sidebar.slider(
    "State of Charge (SOC)",
    0.0,
    100.0,
    85.0,
    1.0
)

current = st.sidebar.slider(
    "Current",
    0.0,
    20.0,
    5.0,
    0.5
)
if mode == "Charging":
    current_direction = 1
else:
    current_direction = -1

cycles = st.sidebar.slider(
    "Battery Cycles",
    0,
    1000,
    100,
    10
)


# =====================================================
# SOH CALCULATION
# =====================================================

# Simple capacity degradation model
capacity_loss = cycles * 0.005

available_capacity = rated_capacity - capacity_loss

available_capacity = max(
    available_capacity,
    rated_capacity * 0.70
)

soh = (
    available_capacity /
    rated_capacity
) * 100


# =====================================================
# VOLTAGE CALCULATION
# =====================================================

min_voltage = 3.0
max_voltage = 4.2

voltage = min_voltage + (
    (max_voltage - min_voltage)
    * soc / 100
)


# =====================================================
# THERMAL MODEL
# =====================================================

# Heat generated by battery

heat_generation = (
    current ** 2
) * internal_resistance


# Simulated temperature

ambient_temperature = 25.0

temperature = (
    ambient_temperature
    + heat_generation * 4
)


# =====================================================
# COOLING SYSTEM
# =====================================================

if temperature >= 45:

    cooling_status = "COOLING ACTIVE"

    cooled_temperature = temperature - 8

else:

    cooling_status = "COOLING OFF"

    cooled_temperature = temperature


# =====================================================
# FAULT DETECTION
# =====================================================

faults = []


if voltage >= 4.2:

    faults.append("OVER VOLTAGE")


if voltage <= 3.0:

    faults.append("UNDER VOLTAGE")


if current > 15:

    faults.append("OVER CURRENT")


if cooled_temperature >= 60:

    faults.append("CRITICAL TEMPERATURE")


# =====================================================
# CELL MONITORING
# =====================================================

cell_voltages = {

    "Cell 1": 4.10,
    "Cell 2": 4.05,
    "Cell 3": 3.95,
    "Cell 4": 4.15

}


max_cell_voltage = max(
    cell_voltages.values()
)

min_cell_voltage = min(
    cell_voltages.values()
)

cell_difference = (
    max_cell_voltage -
    min_cell_voltage
)


if cell_difference > 0.10:

    faults.append("CELL IMBALANCE")

# =====================================================
# BATTERY PACK
# =====================================================

st.divider()

st.subheader("Battery Pack")

pack_cells = {
    "Cell 1": 4.10,
    "Cell 2": 4.05,
    "Cell 3": 3.95,
    "Cell 4": 4.15
}

pack_voltage = sum(pack_cells.values())

st.metric(
    "Total Pack Voltage",
    f"{pack_voltage:.2f} V"
)

st.write("Pack Configuration: **4S1P**")

for cell, v in pack_cells.items():

    if v > 4.10:
        status = "BALANCING"
    else:
        status = "NORMAL"

    st.write(
        f"**{cell}** → {v:.2f} V → {status}"
    )
    # =====================================================
# FAULT LOG
# =====================================================

st.divider()

st.subheader("BMS Fault Log")

fault_log = []

if voltage >= 4.2:
    fault_log.append("OVER VOLTAGE")

if voltage <= 3.0:
    fault_log.append("UNDER VOLTAGE")

if current > 15:
    fault_log.append("OVER CURRENT")

if cooled_temperature >= 60:
    fault_log.append("OVER TEMPERATURE")

if cell_difference > 0.10:
    fault_log.append("CELL IMBALANCE")


if len(fault_log) == 0:

    st.success("No faults recorded.")

else:

    for fault in fault_log:

        st.error(
            f"FAULT DETECTED: {fault}"
        )
# =====================================================
# BMS STATUS
# =====================================================

if len(faults) == 0:

    bms_status = "NORMAL"

else:

    bms_status = "FAULT DETECTED"


# =====================================================
# MAIN DASHBOARD
# =====================================================

col1, col2, col3, col4 = st.columns(4)


with col1:

    st.metric(
        "SOC",
        f"{soc:.1f}%"
    )


with col2:

    st.metric(
        "SOH",
        f"{soh:.1f}%"
    )


with col3:

    st.metric(
        "Voltage",
        f"{voltage:.2f} V"
    )


with col4:

    st.metric(
        "Temperature",
        f"{cooled_temperature:.1f} °C"
    )


# =====================================================
# SECOND ROW
# =====================================================

st.divider()

col5, col6, col7 = st.columns(3)


with col5:

    st.metric(
        "Current",
        f"{current:.1f} A"
    )


with col6:

    st.metric(
        "Available Capacity",
        f"{available_capacity:.2f} Ah"
    )


with col7:

    st.metric(
        "BMS Status",
        bms_status
    )


# =====================================================
# THERMAL MANAGEMENT
# =====================================================

st.divider()

st.subheader("Thermal Management")


col8, col9 = st.columns(2)


with col8:

    st.metric(
        "Heat Generation",
        f"{heat_generation:.2f} W"
    )


with col9:

    st.metric(
        "Cooling Status",
        cooling_status
    )


if cooling_status == "COOLING ACTIVE":

    st.warning(
        "Battery temperature is high. "
        "Cooling system activated."
    )

else:

    st.success(
        "Battery temperature is within safe range."
    )


# =====================================================
# SAFETY MONITORING
# =====================================================

st.divider()

st.subheader("BMS Safety Monitoring")


if len(faults) == 0:

    st.success(
        "No faults detected. Battery operating normally."
    )

else:

    st.error(
        "Battery fault detected!"
    )

    for fault in faults:

        st.warning(fault)


# =====================================================
# CELL MONITORING
# =====================================================

st.divider()

st.subheader("Cell Monitoring")


cell_data = []


for cell, cell_voltage in cell_voltages.items():

    if cell_voltage > 4.10:

        status = "BALANCING"

    elif cell_voltage < 3.0:

        status = "FAULT"

    else:

        status = "NORMAL"


    cell_data.append({

        "Cell": cell,

        "Voltage":
        f"{cell_voltage:.2f} V",

        "Status":
        status

    })


st.dataframe(
    pd.DataFrame(cell_data),
    use_container_width=True
)


st.write(
    f"Cell voltage difference: "
    f"**{cell_difference:.2f} V**"
)


# =====================================================
# SOH INFORMATION
# =====================================================

st.divider()

st.subheader("Battery Health")


st.write(
    f"Battery has completed **{cycles} cycles**."
)

st.write(
    f"Estimated battery health (SOH): "
    f"**{soh:.2f}%**"
)

st.progress(
    int(soh)
)


# =====================================================
# SOC DISCHARGE GRAPH
# =====================================================

st.divider()

st.subheader("SOC Simulation")


time = np.arange(
    0,
    3600,
    10
)


sim_soc = soc + (
    time *
    current *
    current_direction /
    (rated_capacity * 3600)
    * 100
)


sim_soc = np.clip(
    sim_soc,
    0,
    100
)


soc_data = pd.DataFrame({

    "Time (seconds)": time,

    "SOC (%)": sim_soc

})


st.line_chart(
    soc_data,
    x="Time (seconds)",
    y="SOC (%)"
)


# =====================================================
# TEMPERATURE GRAPH
# =====================================================

st.subheader("Temperature Simulation")


sim_heat = (
    current ** 2
) * internal_resistance


sim_temperature = (
    ambient_temperature
    + sim_heat * 4
)


temperature_data = pd.DataFrame({

    "Time (seconds)": time,

    "Temperature (°C)":
    np.full(
        len(time),
        sim_temperature
    )

})


st.line_chart(
    temperature_data,
    x="Time (seconds)",
    y="Temperature (°C)"
)